function adjusted = benjaminiHochberg(pValues)
adjusted = nan(size(pValues));
valid = isfinite(pValues);
validP = pValues(valid);
numberTests = numel(validP);
if numberTests == 0
    return
end
[sortedP, order] = sort(validP);
sortedAdjusted = sortedP .* numberTests ./ transpose(1:numberTests);sortedAdjusted = flipud(cummin(flipud(sortedAdjusted)));
sortedAdjusted = min(sortedAdjusted, 1);
unsortedAdjusted = nan(numberTests, 1);
unsortedAdjusted(order) = sortedAdjusted;
adjusted(valid) = unsortedAdjusted;
end


