function name = findColumn(variableNames, candidates)
name = "";
normalized = lower(regexprep(variableNames, '[^a-zA-Z0-9]', ''));
for candidate = candidates
    key = lower(regexprep(candidate, '[^a-zA-Z0-9]', ''));
    index = find(normalized == key, 1);
    if ~isempty(index)
        name = variableNames(index);
        return
    end
end
end


