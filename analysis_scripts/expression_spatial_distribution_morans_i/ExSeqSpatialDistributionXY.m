function indices = evenlySpacedIndices(numberValues, maximumValues)
if numberValues == 0
    indices = [];
elseif numberValues <= maximumValues
    indices = (1:numberValues)';
else
    indices = unique(round(linspace(1, numberValues, maximumValues)))';
end
end


