function [average, sem] = meanAndSem(curves)
average = mean(curves, 1, 'omitnan');
numberAnimals = sum(all(isfinite(curves), 2));
if numberAnimals <= 1
    sem = zeros(size(average));
else
    sem = std(curves, 0, 1, 'omitnan') ./ sqrt(numberAnimals);
end
end


