function [curves, valid, commonBandwidth] = calculateAnimalKdes( ...
        targetData, fieldName, evaluationGrid)
numberAnimals = numel(targetData);
valid = false(numberAnimals, 1);
individualBandwidths = nan(numberAnimals, 1);
for animalIndex = 1:numberAnimals
    values = targetData(animalIndex).(fieldName);
    values = values(isfinite(values));
    valid(animalIndex) = ~isempty(values);
    if numel(values) >= 2 && range(values) > 0
        [~, ~, individualBandwidths(animalIndex)] = ksdensity(values);
    end
end
commonBandwidth = median(individualBandwidths, 'omitnan');
if ~isfinite(commonBandwidth) || commonBandwidth <= 0
    commonBandwidth = range(evaluationGrid) ./ 30;
end

curves = nan(numberAnimals, numel(evaluationGrid));
for animalIndex = find(valid)'
    values = targetData(animalIndex).(fieldName);
    values = values(isfinite(values));
    curve = ksdensity(values, evaluationGrid, ...
        'Bandwidth', commonBandwidth);
    curveArea = trapz(evaluationGrid, curve);
    if isfinite(curveArea) && curveArea > 0
        curve = curve ./ curveArea;
    end
    curves(animalIndex, :) = curve;
end
end


function model = prepareVoxelBackgroundModel( ...
        voxelMaps, geneName, regionName, groups, numberGridPoints, ...
        minimumMolecules, minimumOccupiedVoxels)
numberAnimals = numel(voxelMaps);
emptyAnimal = struct( ...
    'group', "", 'regionAvailable', false, ...
    'targetMoleculeCount', 0, 'targetOccupiedVoxels', 0, ...
    'backgroundEligibleVoxels', 0, 'valid', false, ...
    'invalidReason', "", ...
    'targetClusterCounts', zeros(0, 1), ...
    'targetX', zeros(0, 1), 'targetY', zeros(0, 1), ...
    'backgroundWeights', zeros(0, 1), ...
    'backgroundX', zeros(0, 1), 'backgroundY', zeros(0, 1));
animalData = repmat(emptyAnimal, numberAnimals, 1);
allX = [];
allY = [];

for animalIndex = 1:numberAnimals
    map = voxelMaps(animalIndex);
    animal = emptyAnimal;
    animal.group = groups(animalIndex);
    if ~map.analysisIncluded
        animal.invalidReason = "animal excluded by registration QC";
        animalData(animalIndex) = animal;
        continue
    end

    regionRows = map.regions == regionName;
    animal.regionAvailable = any(regionRows);
    if ~animal.regionAvailable
        animal.invalidReason = "region absent";
        animalData(animalIndex) = animal;
        continue
    end

    targetRows = regionRows & map.genes == geneName;
    targetCounts = map.moleculeCounts(targetRows);
    animal.targetMoleculeCount = sum(targetCounts);
    animal.targetOccupiedVoxels = numel(targetCounts);
    if ~isempty(targetCounts)
        animal.targetClusterCounts = targetCounts;
        animal.targetX = map.sumReferenceX(targetRows) ./ targetCounts;
        animal.targetY = map.sumReferenceY(targetRows) ./ targetCounts;
    end

    backgroundRows = regionRows & map.genes ~= geneName;
    if any(backgroundRows)
        [backgroundGroup, ~, ~, ~] = findgroups( ...
            map.sectionIndices(backgroundRows), ...
            map.voxelX(backgroundRows), map.voxelY(backgroundRows));
        backgroundCounts = splitapply( ...
            @sum, map.moleculeCounts(backgroundRows), backgroundGroup);
        backgroundSumX = splitapply( ...
            @sum, map.sumReferenceX(backgroundRows), backgroundGroup);
        backgroundSumY = splitapply( ...
            @sum, map.sumReferenceY(backgroundRows), backgroundGroup);
        animal.backgroundEligibleVoxels = numel(backgroundCounts);
        animal.backgroundWeights = backgroundCounts ./ ...
            sum(backgroundCounts);
        animal.backgroundX = backgroundSumX ./ backgroundCounts;
        animal.backgroundY = backgroundSumY ./ backgroundCounts;
    end

    if animal.targetMoleculeCount < minimumMolecules
        animal.invalidReason = "fewer than minimum target molecules";
    elseif animal.targetOccupiedVoxels < minimumOccupiedVoxels
        animal.invalidReason = "fewer than minimum occupied target voxels";
    elseif animal.backgroundEligibleVoxels < ...
            animal.targetOccupiedVoxels
        animal.invalidReason = ...
            "fewer eligible background voxels than target clusters";
    else
        animal.valid = true;
        allX = [allX; animal.targetX; animal.backgroundX]; %#ok<AGROW>
        allY = [allY; animal.targetY; animal.backgroundY]; %#ok<AGROW>
    end
    animalData(animalIndex) = animal;
end

xGrid = makeCoordinateGrid(allX, numberGridPoints);
yGrid = makeCoordinateGrid(allY, numberGridPoints);
valid = reshape([animalData.valid], [], 1);
validGroups = groups(valid);
numberWT = sum(validGroups == "WT");
numberFAD = sum(validGroups == "FAD");

animalCdfX = nan(numberAnimals, numberGridPoints);
animalCdfY = nan(numberAnimals, numberGridPoints);
for animalIndex = find(valid)'
    animal = animalData(animalIndex);
    animalCdfX(animalIndex, :) = weightedSpatialCdf( ...
        animal.targetX, animal.targetClusterCounts, xGrid);
    animalCdfY(animalIndex, :) = weightedSpatialCdf( ...
        animal.targetY, animal.targetClusterCounts, yGrid);
end

if numberWT >= 2 && numberFAD >= 2
    observedX = max(abs( ...
        mean(animalCdfX(valid & groups == "WT", :), 1) - ...
        mean(animalCdfX(valid & groups == "FAD", :), 1)));
    observedY = max(abs( ...
        mean(animalCdfY(valid & groups == "WT", :), 1) - ...
        mean(animalCdfY(valid & groups == "FAD", :), 1)));
    testable = true;
else
    observedX = NaN;
    observedY = NaN;
    testable = false;
end

sampleIndex = (1:numberAnimals)';
regionAvailable = reshape([animalData.regionAvailable], [], 1);
targetMoleculeCount = reshape( ...
    [animalData.targetMoleculeCount], [], 1);
targetOccupiedVoxels = reshape( ...
    [animalData.targetOccupiedVoxels], [], 1);
backgroundEligibleVoxels = reshape( ...
    [animalData.backgroundEligibleVoxels], [], 1);
invalidReason = string({animalData.invalidReason})';
animalDiagnostics = table( ...
    sampleIndex, groups, regionAvailable, targetMoleculeCount, ...
    targetOccupiedVoxels, backgroundEligibleVoxels, valid, ...
    invalidReason, ...
    'VariableNames', {'sample_index', 'group', 'region_available', ...
    'target_molecules', 'target_occupied_10um_voxels', ...
    'target_excluded_background_voxels', 'valid_for_test', ...
    'invalid_reason'});

model = struct( ...
    'testable', testable, 'animalData', animalData, ...
    'animalDiagnostics', animalDiagnostics, ...
    'valid', valid, 'groups', groups, ...
    'numberWT', numberWT, 'numberFAD', numberFAD, ...
    'xGrid', xGrid, 'yGrid', yGrid, ...
    'observedX', observedX, 'observedY', observedY);
end


function gridValues = makeCoordinateGrid(values, numberGridPoints)
values = values(isfinite(values));
if isempty(values)
    gridValues = linspace(-0.02, 1.02, numberGridPoints);
    return
end
lower = min([0; values]);
upper = max([1; values]);
padding = 0.02 .* max(upper - lower, 1);
gridValues = linspace(lower - padding, upper + padding, ...
    numberGridPoints);
end


function cdfValues = weightedSpatialCdf(positions, weights, gridValues)
totalWeight = sum(weights);
if isempty(positions) || totalWeight <= 0
    cdfValues = nan(1, numel(gridValues));
    return
end
cdfValues = arrayfun( ...
    @(coordinate) sum(weights(positions <= coordinate)), gridValues);
cdfValues = cdfValues ./ totalWeight;
end


function result = runVoxelBackgroundBootstrap( ...
        model, numberBootstrapReplicates)
result = struct( ...
    'xGrid', model.xGrid, 'yGrid', model.yGrid, ...
    'distanceX', model.observedX, 'distanceY', model.observedY, ...
    'pX', NaN, 'pY', NaN, ...
    'exceedancesX', 0, 'exceedancesY', 0, ...
    'nullMeanX', NaN, 'nullMeanY', NaN, ...
    'nullStdX', NaN, 'nullStdY', NaN, ...
    'numberBootstraps', numberBootstrapReplicates, ...
    'numberWT', model.numberWT, 'numberFAD', model.numberFAD, ...
    'animalDiagnostics', model.animalDiagnostics);
if ~model.testable
    result.numberBootstraps = 0;
    return
end

validIndices = find(model.valid);
validAnimals = model.animalData(validIndices);
validGroups = model.groups(validIndices);
numberGridPoints = numel(model.xGrid);
maximumBackgroundVoxels = max( ...
    [validAnimals.backgroundEligibleVoxels]);
batchSize = max(10, min(250, ...
    floor(2e6 ./ max(maximumBackgroundVoxels, 1))));
nullDistancesX = zeros(numberBootstrapReplicates, 1);
nullDistancesY = zeros(numberBootstrapReplicates, 1);
numberCompleted = 0;

while numberCompleted < numberBootstrapReplicates
    currentBatch = min(batchSize, ...
        numberBootstrapReplicates - numberCompleted);
    wtCdfSumX = zeros(currentBatch, numberGridPoints);
    wtCdfSumY = zeros(currentBatch, numberGridPoints);
    fadCdfSumX = zeros(currentBatch, numberGridPoints);
    fadCdfSumY = zeros(currentBatch, numberGridPoints);

    for animalIndex = 1:numel(validAnimals)
        animal = validAnimals(animalIndex);
        numberClusters = animal.targetOccupiedVoxels;
        selectedVoxels = weightedSampleWithoutReplacementRows( ...
            animal.backgroundWeights, numberClusters, currentBatch);
        if numberClusters == 1
            assignedCounts = repmat( ...
                animal.targetClusterCounts', currentBatch, 1);
        else
            [~, permutationOrder] = sort( ...
                rand(currentBatch, numberClusters), 2);
            assignedCounts = animal.targetClusterCounts( ...
                permutationOrder);
        end

        xBins = coordinateBins( ...
            animal.backgroundX, model.xGrid);
        yBins = coordinateBins( ...
            animal.backgroundY, model.yGrid);
        replicateIndex = repmat((1:currentBatch)', 1, numberClusters);
        histogramX = accumarray( ...
            [replicateIndex(:), xBins(selectedVoxels(:))], ...
            assignedCounts(:), ...
            [currentBatch, numberGridPoints]);
        histogramY = accumarray( ...
            [replicateIndex(:), yBins(selectedVoxels(:))], ...
            assignedCounts(:), ...
            [currentBatch, numberGridPoints]);
        cdfX = cumsum(histogramX, 2) ./ ...
            animal.targetMoleculeCount;
        cdfY = cumsum(histogramY, 2) ./ ...
            animal.targetMoleculeCount;
        if validGroups(animalIndex) == "WT"
            wtCdfSumX = wtCdfSumX + cdfX;
            wtCdfSumY = wtCdfSumY + cdfY;
        else
            fadCdfSumX = fadCdfSumX + cdfX;
            fadCdfSumY = fadCdfSumY + cdfY;
        end
    end

    differenceX = wtCdfSumX ./ model.numberWT - ...
        fadCdfSumX ./ model.numberFAD;
    differenceY = wtCdfSumY ./ model.numberWT - ...
        fadCdfSumY ./ model.numberFAD;
    rows = numberCompleted + (1:currentBatch);
    nullDistancesX(rows) = max(abs(differenceX), [], 2);
    nullDistancesY(rows) = max(abs(differenceY), [], 2);
    numberCompleted = numberCompleted + currentBatch;
end

result.exceedancesX = sum( ...
    nullDistancesX >= model.observedX - 1e-12);
result.exceedancesY = sum( ...
    nullDistancesY >= model.observedY - 1e-12);
result.pX = (result.exceedancesX + 1) ./ ...
    (numberBootstrapReplicates + 1);
result.pY = (result.exceedancesY + 1) ./ ...
    (numberBootstrapReplicates + 1);
result.nullMeanX = mean(nullDistancesX);
result.nullMeanY = mean(nullDistancesY);
result.nullStdX = std(nullDistancesX);
result.nullStdY = std(nullDistancesY);
end


function selected = weightedSampleWithoutReplacementRows( ...
        weights, sampleSize, numberRows)
weights = reshape(weights, 1, []);
numberCandidates = numel(weights);
if sampleSize > numberCandidates
    error('Cannot sample more background voxels than are available.');
end
if sampleSize == numberCandidates
    selected = repmat(1:numberCandidates, numberRows, 1);
    return
end
exponentialKeys = -log(max(rand(numberRows, numberCandidates), ...
    realmin('double'))) ./ weights;
[~, selected] = mink(exponentialKeys, sampleSize, 2);
end


function bins = coordinateBins(positions, gridValues)
edges = [-Inf, gridValues(1:end-1), Inf];
bins = discretize(positions, edges);
bins = reshape(bins, [], 1);
end


function result = animalLevelKsTest(targetData, fieldName, groups, gridValues)
numberAnimals = numel(targetData);
individualCdfs = nan(numberAnimals, numel(gridValues));
valid = false(numberAnimals, 1);
pooledWT = [];
pooledFAD = [];
for animalIndex = 1:numberAnimals
    values = targetData(animalIndex).(fieldName);
    values = values(isfinite(values));
    if isempty(values)
        continue
    end
    valid(animalIndex) = true;
    individualCdfs(animalIndex, :) = arrayfun( ...
        @(position) mean(values <= position), gridValues);
    if groups(animalIndex) == "WT"
        pooledWT = [pooledWT; values]; %#ok<AGROW>
    else
        pooledFAD = [pooledFAD; values]; %#ok<AGROW>
    end
end

validIndices = find(valid);
validGroups = groups(valid);
numberWT = sum(validGroups == "WT");
numberFAD = sum(validGroups == "FAD");
if numberWT < 2 || numberFAD < 2
    result = struct( ...
        'distance', NaN, ...
        'permutationP', NaN, ...
        'normalFitP', NaN, ...
        'permutedMean', NaN, ...
        'permutedStd', NaN, ...
        'numberPermutations', 0, ...
        'pooledDistance', NaN, ...
        'pooledP', NaN, ...
        'numberWT', numberWT, ...
        'numberFAD', numberFAD, ...
        'wtMolecules', numel(pooledWT), ...
        'fadMolecules', numel(pooledFAD));
    return
end

meanWT = mean(individualCdfs(valid & groups == "WT", :), 1);
meanFAD = mean(individualCdfs(valid & groups == "FAD", :), 1);
observedDistance = max(abs(meanWT - meanFAD));

combinations = nchoosek(1:numel(validIndices), numberWT);
permutedDistances = zeros(size(combinations, 1), 1);
validCdfs = individualCdfs(validIndices, :);
allIndices = 1:numel(validIndices);
for permutationIndex = 1:size(combinations, 1)
    permutedWT = combinations(permutationIndex, :);
    permutedFAD = setdiff(allIndices, permutedWT);
    difference = mean(validCdfs(permutedWT, :), 1) - ...
        mean(validCdfs(permutedFAD, :), 1);
    permutedDistances(permutationIndex) = max(abs(difference));
end
permutationP = mean(permutedDistances >= observedDistance - 1e-12);
permutedMean = mean(permutedDistances);
permutedStd = std(permutedDistances, 0);
if isfinite(permutedStd) && permutedStd > 0
    zScore = (observedDistance - permutedMean) ./ permutedStd;
    normalFitP = 0.5 .* erfc(zScore ./ sqrt(2));
    normalFitP = max(normalFitP, realmin('double'));
else
    normalFitP = double(observedDistance <= permutedMean);
end

[~, pooledP, pooledDistance] = kstest2(pooledWT, pooledFAD);
result = struct( ...
    'distance', observedDistance, ...
    'permutationP', permutationP, ...
    'normalFitP', normalFitP, ...
    'permutedMean', permutedMean, ...
    'permutedStd', permutedStd, ...
    'numberPermutations', numel(permutedDistances), ...
    'pooledDistance', pooledDistance, ...
    'pooledP', pooledP, ...
    'numberWT', numberWT, ...
    'numberFAD', numberFAD, ...
    'wtMolecules', numel(pooledWT), ...
    'fadMolecules', numel(pooledFAD));
end


