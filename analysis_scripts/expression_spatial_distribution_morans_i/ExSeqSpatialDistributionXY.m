function [statistics, significantPairs] = ExSeqSpatialDistributionXY( ...
        outputFolder, inputFolder, referenceImagePath, callsCsvPath, ...
        bootstrapReplicatesOverride, generateSignificantPlotsOverride)
% ExSeqSpatialDistributionXY
% Screens ExSeq expression and Moran gene-region calls for
% genotype-associated shifts along registered reference-map X and Y axes.
%
% Registration is performed once per animal, before target genes or regions
% are selected:
%   1. All molecules in annotated hippocampal regions are pooled.
%   2. Complementary tissue portions are reassembled.
%   3. A whole-map PCA shape alignment maps the animal to the reference.
%   4. A nonreflective whole-map similarity correction and a smooth global
%      landmark warp are fitted from all shared regional centroids. No
%      region receives an independent coordinate system.
%   5. The registered reference image defines the common X/Y coordinates.
%
% Each animal contributes one equally weighted spatial ECDF. The primary P
% value uses a target-excluded, animal- and region-specific transcript
% background aggregated into 10-um voxels. Every realization preserves the
% exact target molecule count, number of occupied voxels, and observed
% per-voxel cluster-size distribution.

scriptDir = fileparts(mfilename('fullpath'));
if nargin < 1 || strlength(string(outputFolder)) == 0
    outputFolder = fullfile(scriptDir, 'results', 'exseq_spatial_distribution');
end
if nargin < 2 || strlength(string(inputFolder)) == 0
    inputFolder = fullfile(scriptDir, 'data', 'exseq');
end
if nargin < 3 || strlength(string(referenceImagePath)) == 0
    referenceImagePath = fullfile(scriptDir, ...
        'hippocampus_reference_map.png');
end
if nargin < 4 || strlength(string(callsCsvPath)) == 0
    callsCsvPath = fullfile(scriptDir, 'exseq_spatial_calls.csv');
end
if ~isfolder(outputFolder)
    mkdir(outputFolder);
end

targets = readtable(callsCsvPath, 'TextType', 'string');
targets.analysis = lower(strtrim(targets.analysis));
targets.gene = upper(regexprep(strtrim(targets.gene), '\s+', ''));
targets.region = standardizeRegion(targets.region);
nExpressionCalls = sum(targets.analysis == "expression");
nMoranCalls = sum(targets.analysis == "moran");
if nExpressionCalls < 1 && nMoranCalls < 1
    error(['calls CSV must contain at least one row with analysis ' ...
        '"expression" or "moran".']);
end
fprintf('Loaded %d expression calls and %d Moran calls from %s\n', ...
    nExpressionCalls, nMoranCalls, callsCsvPath);
numberGridPoints = 301;
voxelSizeMicrons = 10;
minimumMoleculesPerAnimalRegion = 5;
minimumOccupiedVoxelsPerAnimalRegion = 3;
if nargin < 5 || isempty(bootstrapReplicatesOverride)
    numberBootstrapReplicates = 20000;
else
    numberBootstrapReplicates = bootstrapReplicatesOverride;
end
validateattributes(numberBootstrapReplicates, {'numeric'}, ...
    {'scalar', 'integer', '>=', 100});
if nargin < 6 || isempty(generateSignificantPlotsOverride)
    generateSignificantPlots = false;
else
    generateSignificantPlots = logical(generateSignificantPlotsOverride);
end
bootstrapSeed = 91841;

reference = buildReferenceTemplate(referenceImagePath);
saveReferenceTemplateAudit(reference, outputFolder);

samples = defineExseqSamples();
numberSamples = numel(samples);
numberTargets = height(targets);
emptyTarget = struct( ...
    'geneX', [], 'geneY', [], ...
    'regionAvailable', false, 'moleculeCount', 0);
axisData = repmat(emptyTarget, numberSamples, numberTargets);
emptyAudit = struct('x', [], 'y', [], 'regions', strings(0, 1), ...
    'sectionIndices', [], 'sectionFiles', strings(0, 1), ...
    'initialX', [], 'initialY', [], ...
    'initialRegions', strings(0, 1), ...
    'initialSectionIndices', [], ...
    'registeredCentroids', [], 'referenceCentroids', [], ...
    'sharedRegionNames', strings(0, 1), ...
    'analysisIncluded', true, 'excludedSectionIndices', []);
auditMaps = repmat(emptyAudit, numberSamples, 1);
emptyVoxelMap = struct( ...
    'genes', strings(0, 1), 'regions', strings(0, 1), ...
    'sectionIndices', zeros(0, 1), ...
    'voxelX', zeros(0, 1), 'voxelY', zeros(0, 1), ...
    'moleculeCounts', zeros(0, 1), ...
    'sumReferenceX', zeros(0, 1), ...
    'sumReferenceY', zeros(0, 1), ...
    'analysisIncluded', false);
voxelMaps = repmat(emptyVoxelMap, numberSamples, 1);
qcRows = table();
sectionQcRows = table();

fprintf('Registering %d complete ExSeq animal maps...\n', numberSamples);
for sampleIndex = 1:numberSamples
    fprintf('  %s (%s)\n', samples(sampleIndex).name, ...
        samples(sampleIndex).group);
    [axisData(sampleIndex, :), voxelMaps(sampleIndex), ...
        auditMaps(sampleIndex), qcRow, sampleSectionQc] = ...
        processOneAnimal(samples(sampleIndex), inputFolder, targets, ...
        reference, voxelSizeMicrons);
    qcRows = [qcRows; qcRow]; %#ok<AGROW>
    sectionQcRows = [sectionQcRows; sampleSectionQc]; %#ok<AGROW>
end

registrationFigure = plotRegistrationAudit( ...
    auditMaps, samples, reference, qcRows);
savefig(registrationFigure, fullfile(outputFolder, ...
    'ExSeq_whole_animal_reference_registration_audit.fig'));
exportgraphics(registrationFigure, fullfile(outputFolder, ...
    'ExSeq_whole_animal_reference_registration_audit.tif'), ...
    'Resolution', 300);
close(registrationFigure);

writetable(qcRows, fullfile(outputFolder, ...
    'ExSeq_reference_registration_QC.csv'));
writetable(sectionQcRows, fullfile(outputFolder, ...
    'ExSeq_reference_registration_section_QC.csv'));

sectionFigure = plotSectionRegistrationAudit( ...
    auditMaps, samples, reference, sectionQcRows);
savefig(sectionFigure, fullfile(outputFolder, ...
    'ExSeq_individual_section_registration_audit.fig'));
exportgraphics(sectionFigure, fullfile(outputFolder, ...
    'ExSeq_individual_section_registration_audit.tif'), ...
    'Resolution', 300);
close(sectionFigure);

retainedFigure = plotSectionRegistrationSubset( ...
    auditMaps, samples, reference, qcRows, sectionQcRows, ...
    sectionQcRows.analysis_included, true, ...
    'Retained tissue-part registrations used in the analysis');
savefig(retainedFigure, fullfile(outputFolder, ...
    'ExSeq_retained_section_registrations.fig'));
exportgraphics(retainedFigure, fullfile(outputFolder, ...
    'ExSeq_retained_section_registrations.tif'), ...
    'Resolution', 300);
close(retainedFigure);

discardedFigure = plotSectionRegistrationSubset( ...
    auditMaps, samples, reference, qcRows, sectionQcRows, ...
    ~sectionQcRows.analysis_included, false, ...
    'Discarded tissue-part registrations');
savefig(discardedFigure, fullfile(outputFolder, ...
    'ExSeq_discarded_section_registrations.fig'));
exportgraphics(discardedFigure, fullfile(outputFolder, ...
    'ExSeq_discarded_section_registrations.tif'), ...
    'Resolution', 300);
close(discardedFigure);

groups = string({samples.group})';
sampleNames = string({samples.name})';
sampleIncluded = qcRows.analysis_included;
statistics = table();
countRows = table();
voxelDiagnosticRows = table();
voxelTests = cell(numberTargets, 1);
testCache = containers.Map('KeyType', 'char', 'ValueType', 'any');
for targetIndex = 1:numberTargets
    analysisName = targets.analysis(targetIndex);
    geneName = targets.gene(targetIndex);
    regionName = targets.region(targetIndex);
    targetData = axisData(:, targetIndex);
    moleculeCounts = reshape([targetData.moleculeCount], [], 1);
    regionAvailable = reshape([targetData.regionAvailable], [], 1);
    countRows = [countRows; table( ... %#ok<AGROW>
        repmat(analysisName, numberSamples, 1), ...
        repmat(geneName, numberSamples, 1), ...
        repmat(regionName, numberSamples, 1), ...
        sampleNames, groups, sampleIncluded, ...
        regionAvailable, moleculeCounts, ...
        'VariableNames', {'analysis', 'gene', 'region', ...
        'sample', 'group', ...
        'analysis_included', 'region_available', ...
        'gene_molecule_count'})];

    cacheKey = char(geneName + "|" + regionName);
    if isKey(testCache, cacheKey)
        test = testCache(cacheKey);
    else
        model = prepareVoxelBackgroundModel( ...
            voxelMaps, geneName, regionName, groups, ...
            numberGridPoints, minimumMoleculesPerAnimalRegion, ...
            minimumOccupiedVoxelsPerAnimalRegion);
        rng(bootstrapSeed + targetIndex, 'twister');
        test = runVoxelBackgroundBootstrap( ...
            model, numberBootstrapReplicates);
        testCache(cacheKey) = test;
    end
    voxelTests{targetIndex} = test;

    exactX = animalLevelKsTest( ...
        targetData, 'geneX', groups, test.xGrid);
    exactY = animalLevelKsTest( ...
        targetData, 'geneY', groups, test.yGrid);
    [xRow, yRow] = makeVoxelStatisticsRows( ...
        geneName, regionName, test, exactX, exactY, ...
        voxelSizeMicrons, minimumMoleculesPerAnimalRegion, ...
        minimumOccupiedVoxelsPerAnimalRegion);
    xRow = addvars(xRow, analysisName, targetIndex, ...
        'Before', 'gene', ...
        'NewVariableNames', {'analysis', 'target_index'});
    yRow = addvars(yRow, analysisName, targetIndex, ...
        'Before', 'gene', ...
        'NewVariableNames', {'analysis', 'target_index'});
    statistics = [statistics; xRow; yRow]; %#ok<AGROW>

    animalDiagnostics = test.animalDiagnostics;
    animalDiagnostics = addvars(animalDiagnostics, ...
        repmat(analysisName, height(animalDiagnostics), 1), ...
        repmat(geneName, height(animalDiagnostics), 1), ...
        repmat(regionName, height(animalDiagnostics), 1), ...
        sampleNames(animalDiagnostics.sample_index), ...
        'Before', 1, ...
        'NewVariableNames', {'analysis', 'gene', 'region', 'sample'});
    voxelDiagnosticRows = [voxelDiagnosticRows; ...
        animalDiagnostics]; %#ok<AGROW>
end

statistics.BH_FDR_within_analysis = nan(height(statistics), 1);
analysisFamilies = ["expression", "moran"];
for analysisName = analysisFamilies
    rows = statistics.analysis == analysisName;
    statistics.BH_FDR_within_analysis(rows) = ...
        benjaminiHochberg( ...
        statistics.voxel_background_p(rows));
end
statistics.BH_FDR_all_232_axis_tests = benjaminiHochberg( ...
    statistics.voxel_background_p);
statistics.significant_BH_0p05 = ...
    statistics.BH_FDR_within_analysis <= 0.05;

xRows = 1:2:height(statistics);
yRows = 2:2:height(statistics);
significantPairs = table( ...
    (1:numberTargets)', targets.analysis, targets.gene, targets.region, ...
    statistics.voxel_level_KS_D(xRows), ...
    statistics.voxel_background_p(xRows), ...
    statistics.animal_label_permutation_p(xRows), ...
    statistics.BH_FDR_within_analysis(xRows), ...
    statistics.voxel_level_KS_D(yRows), ...
    statistics.voxel_background_p(yRows), ...
    statistics.animal_label_permutation_p(yRows), ...
    statistics.BH_FDR_within_analysis(yRows), ...
    statistics.significant_BH_0p05(xRows), ...
    statistics.significant_BH_0p05(yRows), ...
    'VariableNames', {'target_index', 'analysis', 'gene', 'region', ...
    'voxel_KS_D_X', 'voxel_background_p_X', ...
    'exact_permutation_p_X', 'BH_FDR_X', ...
    'voxel_KS_D_Y', 'voxel_background_p_Y', ...
    'exact_permutation_p_Y', 'BH_FDR_Y', ...
    'significant_X', 'significant_Y'});
significantPairs.significant_either_axis = ...
    significantPairs.significant_X | significantPairs.significant_Y;
significantAxis = repmat("none", numberTargets, 1);
significantAxis(significantPairs.significant_X) = "X";
significantAxis(significantPairs.significant_Y) = "Y";
significantAxis(significantPairs.significant_X & ...
    significantPairs.significant_Y) = "X;Y";
significantPairs.significant_axis = significantAxis;

writetable(statistics, fullfile(outputFolder, ...
    'ExSeq_spatial_axis_all_axis_tests_with_BH.csv'));
writetable(significantPairs, fullfile(outputFolder, ...
    'ExSeq_spatial_axis_gene_region_summary.csv'));
writetable(countRows, fullfile(outputFolder, ...
    'ExSeq_reference_registered_per_animal_molecule_counts.csv'));
writetable(voxelDiagnosticRows, fullfile(outputFolder, ...
    'ExSeq_voxel_background_per_animal_diagnostics.csv'));
methodParameters = table( ...
    voxelSizeMicrons, minimumMoleculesPerAnimalRegion, ...
    minimumOccupiedVoxelsPerAnimalRegion, ...
    numberBootstrapReplicates, bootstrapSeed, ...
    "target-excluded all-gene background", ...
    "weighted without replacement", ...
    'VariableNames', {'voxel_size_um', ...
    'minimum_target_molecules_per_animal_region', ...
    'minimum_occupied_target_voxels_per_animal_region', ...
    'bootstrap_replicates', 'bootstrap_seed', ...
    'background_definition', 'voxel_sampling'});
writetable(methodParameters, fullfile(outputFolder, ...
    'ExSeq_voxel_background_method_parameters.csv'));

significantTargetIndices = find( ...
    significantPairs.significant_either_axis);
if generateSignificantPlots
for targetIndex = reshape(significantTargetIndices, 1, [])
    targetData = axisData(:, targetIndex);
    test = voxelTests{targetIndex};
    xGrid = test.xGrid;
    yGrid = test.yGrid;
    [xCurves, xValid, xBandwidth] = calculateAnimalKdes( ...
        targetData, 'geneX', xGrid);
    [yCurves, yValid, yBandwidth] = calculateAnimalKdes( ...
        targetData, 'geneY', yGrid);
    xTest = makeVoxelPlotTest(test, "X");
    yTest = makeVoxelPlotTest(test, "Y");
    fig = plotTargetFigure( ...
        targets.analysis(targetIndex), ...
        targets.gene(targetIndex), targets.region(targetIndex), samples, ...
        xGrid, xCurves, xValid, xBandwidth, xTest, ...
        significantPairs.BH_FDR_X(targetIndex), ...
        yGrid, yCurves, yValid, yBandwidth, yTest, ...
        significantPairs.BH_FDR_Y(targetIndex));
    stem = sprintf('%s_%s_%s_voxel_background_BH_significant_KDE', ...
        sanitizeName(targets.analysis(targetIndex)), ...
        sanitizeName(targets.gene(targetIndex)), ...
        sanitizeName(targets.region(targetIndex)));
    savefig(fig, fullfile(outputFolder, stem + ".fig"));
    exportgraphics(fig, fullfile(outputFolder, stem + ".tif"), ...
        'Resolution', 300);
    close(fig);
end
end

fprintf(['\nTested %d gene-region calls (%d axis tests); ' ...
    '%d pairs passed BH FDR <= 0.05 in either axis.\nSaved to:\n%s\n'], ...
    numberTargets, height(statistics), numel(significantTargetIndices), ...
    outputFolder);
disp(qcRows);
disp(significantPairs(significantPairs.significant_either_axis, :));
end


function reference = buildReferenceTemplate(referenceImagePath)
if ~isfile(referenceImagePath)
    error('Reference image not found: %s', referenceImagePath);
end
imageRgb = imread(referenceImagePath);
[height, width, ~] = size(imageRgb);
imageLab = rgb2lab(im2double(imageRgb));
pixels = reshape(imageLab, [], 3);
rng(17, 'twister');
[clusterIndex, centersLab] = kmeans(pixels, 18, ...
    'MaxIter', 600, 'Replicates', 5);
centersRgb = reshape(lab2rgb(reshape(centersLab, [], 1, 3)), [], 3);
centersRgb = centersRgb .* 255;

regionNames = ["SO"; "CA1"; "DG-CA1"; "SLM"; "DG"; "Hilus"; "CA3"];
prototypeRgb = [ ...
    172, 207, 136; ...
    185,  48, 206; ...
     93, 186, 230; ...
    240, 199,  97; ...
    165,  88,  74; ...
    185,  71,  71; ...
    229, 224,  93];

numberRegions = numel(regionNames);
masks = false(height, width, numberRegions);
usedClusters = false(size(centersRgb, 1), 1);
clusterForRegion = zeros(numberRegions, 1);
for regionIndex = 1:numberRegions
    distances = vecnorm(centersRgb - prototypeRgb(regionIndex, :), 2, 2);
    distances(usedClusters) = inf;
    [~, selectedCluster] = min(distances);
    usedClusters(selectedCluster) = true;
    clusterForRegion(regionIndex) = selectedCluster;
    mask = reshape(clusterIndex == selectedCluster, height, width);
    mask = imclose(mask, strel('disk', 2, 0));
    mask = bwareaopen(mask, 25);
    mask = imfill(mask, 'holes');
    if any(mask, 'all')
        mask = bwpropfilt(mask, 'Area', 1);
    end
    masks(:, :, regionIndex) = mask;
end

centroids = nan(numberRegions, 2);
for regionIndex = 1:numberRegions
    [rows, columns] = find(masks(:, :, regionIndex));
    centroids(regionIndex, :) = [ ...
        mean(columns), height + 1 - mean(rows)];
end
unionMask = any(masks, 3);
[unionRows, unionColumns] = find(unionMask);
unionPoints = [unionColumns, height + 1 - unionRows];

reference = struct( ...
    'imageRgb', imageRgb, ...
    'height', height, ...
    'width', width, ...
    'regionNames', regionNames, ...
    'prototypeRgb', prototypeRgb, ...
    'clusterForRegion', clusterForRegion, ...
    'masks', masks, ...
    'centroids', centroids, ...
    'unionMask', unionMask, ...
    'unionPoints', unionPoints);
end


function saveReferenceTemplateAudit(reference, outputFolder)
fig = figure('Color', 'w', 'Position', [80, 80, 1050, 440]);
layout = tiledlayout(fig, 1, 2, ...
    'TileSpacing', 'compact', 'Padding', 'compact');

ax1 = nexttile(layout);
image(ax1, [1, reference.width], [1, reference.height], ...
    flipud(reference.imageRgb));
set(ax1, 'YDir', 'normal');
axis(ax1, 'image');
title(ax1, 'Supplied reference map');
xlabel(ax1, 'Reference X (pixels)');
ylabel(ax1, 'Reference Y (pixels)');

ax2 = nexttile(layout);
labelImage = ones(reference.height, reference.width, 3);
for regionIndex = 1:numel(reference.regionNames)
    mask = reference.masks(:, :, regionIndex);
    color = reference.prototypeRgb(regionIndex, :) ./ 255;
    for channel = 1:3
        layer = labelImage(:, :, channel);
        layer(mask) = color(channel);
        labelImage(:, :, channel) = layer;
    end
end
image(ax2, [1, reference.width], [1, reference.height], ...
    flipud(labelImage));
set(ax2, 'YDir', 'normal');
axis(ax2, 'image');
hold(ax2, 'on');
for regionIndex = 1:numel(reference.regionNames)
    centroid = reference.centroids(regionIndex, :);
    plot(ax2, centroid(1), centroid(2), 'ko', ...
        'MarkerFaceColor', 'w', 'MarkerSize', 5);
    text(ax2, centroid(1) + 3, centroid(2), ...
        reference.regionNames(regionIndex), ...
        'FontSize', 8, 'FontWeight', 'bold');
end
title(ax2, 'Color-derived reference labels and centroids');
xlabel(ax2, 'Reference X (pixels)');
ylabel(ax2, 'Reference Y (pixels)');
title(layout, 'Reference-template extraction used for registration', ...
    'FontSize', 14, 'FontWeight', 'bold');

savefig(fig, fullfile(outputFolder, ...
    'hippocampus_reference_template_extraction.fig'));
exportgraphics(fig, fullfile(outputFolder, ...
    'hippocampus_reference_template_extraction.tif'), ...
    'Resolution', 300);
close(fig);
end


function [targetData, voxelMap, auditMap, qcRow, sectionQcRows] = ...
        processOneAnimal(sample, inputFolder, targets, reference, ...
        voxelSizeMicrons)
rawMap = loadAndReassembleWholeAnimal(sample, inputFolder, reference);
[initialRegisteredCoordinates, initialRegistration] = registerWholeMap( ...
    rawMap.coordinates, rawMap.regions, reference);
sectionQcRows = makeSectionQcRows( ...
    sample, rawMap, initialRegisteredCoordinates, reference);

if rawMap.numberSectionsPresent > 1
    % Disconnected tissue pieces require separate rigid/global placements
    % after their requested orientation corrections. They are combined
    % only after each complete piece is mapped to the same reference.
    badSectionRows = ...
        sectionQcRows.number_shared_regions < 2 | ...
        sectionQcRows. ...
        independent_fraction_within_5px_of_matching_region < 0.50;
    grossSingleSectionFailure = false;
else
    badSectionRows = false(height(sectionQcRows), 1);
    grossSingleSectionFailure = ...
        initialRegistration.centroidRmsePixels > 50 && ...
        initialRegistration.affineDeterminant < 0.05;
end
manualDiscardRows = ...
    (string(sample.name) == "FAD1" & ...
    sectionQcRows.section_index == 1) | ...
    (string(sample.name) == "FAD6" & ...
    sectionQcRows.section_index == 1) | ...
    (string(sample.name) == "FAD5" & ...
    sectionQcRows.section_index == 1) | ...
    string(sample.name) == "WT6";
badSectionRows = badSectionRows | manualDiscardRows;
excludedSectionIndices = sectionQcRows.section_index(badSectionRows);
keptSectionMask = ~ismember(rawMap.sectionIndices, ...
    excludedSectionIndices);
analysisIncluded = any(keptSectionMask) && ...
    ~grossSingleSectionFailure;

exclusionReason = "";
if grossSingleSectionFailure
    exclusionReason = ...
        "gross whole-map fit failure (collapsed scale and centroid error)";
elseif ~any(keptSectionMask)
    if any(manualDiscardRows)
        exclusionReason = ...
            "all available tissue parts were manually excluded";
    else
        exclusionReason = ...
            "no independently registerable tissue part remains";
    end
end

sectionQcRows.part_excluded_for_misregistration = badSectionRows;
sectionQcRows.animal_excluded = ...
    repmat(~analysisIncluded, height(sectionQcRows), 1);
sectionQcRows.analysis_included = ...
    ~badSectionRows & analysisIncluded;
sectionQcRows.exclusion_reason = repmat("", height(sectionQcRows), 1);
sectionQcRows.exclusion_reason(badSectionRows) = ...
    "fewer than two regions or independent matching below 50%";
sectionQcRows.exclusion_reason(manualDiscardRows) = ...
    "manually discarded before analysis";
if ~analysisIncluded
    sectionQcRows.exclusion_reason(~badSectionRows) = exclusionReason;
end

if analysisIncluded
    analysisMap = subsetRawMap(rawMap, keptSectionMask);
    if rawMap.numberSectionsPresent > 1
        [registeredCoordinates, registration] = ...
            registerTissuePartsToCommonReference(analysisMap, reference);
    else
        registeredCoordinates = initialRegisteredCoordinates;
        registration = initialRegistration;
    end
else
    % Retain the failed initial placement only for the diagnostic audit.
    analysisMap = rawMap;
    registeredCoordinates = initialRegisteredCoordinates;
    registration = initialRegistration;
end

xReference = (registeredCoordinates(:, 1) - 1) ./ ...
    (reference.width - 1);
yReference = (registeredCoordinates(:, 2) - 1) ./ ...
    (reference.height - 1);

numberTargets = height(targets);
emptyTarget = struct( ...
    'geneX', [], 'geneY', [], ...
    'regionAvailable', false, 'moleculeCount', 0);
targetData = repmat(emptyTarget, 1, numberTargets);
if analysisIncluded
    for targetIndex = 1:numberTargets
        regionMask = analysisMap.regions == targets.region(targetIndex);
        geneMask = regionMask & ...
            analysisMap.genes == targets.gene(targetIndex);
        targetData(targetIndex) = struct( ...
            'geneX', xReference(geneMask), ...
            'geneY', yReference(geneMask), ...
            'regionAvailable', any(regionMask), ...
            'moleculeCount', sum(geneMask));
    end
end

voxelMap = aggregateGeneVoxels( ...
    analysisMap, xReference, yReference, analysisIncluded, ...
    voxelSizeMicrons);

auditKeep = evenlySpacedIndices(numel(xReference), 32000);
initialAuditKeep = evenlySpacedIndices( ...
    size(initialRegisteredCoordinates, 1), 32000);
auditMap = struct( ...
    'x', registeredCoordinates(auditKeep, 1), ...
    'y', registeredCoordinates(auditKeep, 2), ...
    'regions', analysisMap.regions(auditKeep), ...
    'sectionIndices', analysisMap.sectionIndices(auditKeep), ...
    'sectionFiles', analysisMap.sectionFiles(auditKeep), ...
    'initialX', initialRegisteredCoordinates(initialAuditKeep, 1), ...
    'initialY', initialRegisteredCoordinates(initialAuditKeep, 2), ...
    'initialRegions', rawMap.regions(initialAuditKeep), ...
    'initialSectionIndices', rawMap.sectionIndices(initialAuditKeep), ...
    'analysisIncluded', analysisIncluded, ...
    'excludedSectionIndices', excludedSectionIndices, ...
    'registeredCentroids', registration.registeredCentroids, ...
    'referenceCentroids', registration.referenceCentroids, ...
    'sharedRegionNames', registration.sharedRegionNames);

qcKeep = evenlySpacedIndices(numel(xReference), 120000);
[insideFraction, matchingFraction, medianMatchingDistance] = ...
    registrationCoverage( ...
    registeredCoordinates(qcKeep, :), ...
    analysisMap.regions(qcKeep), reference);
qcRow = table( ...
    string(sample.name), string(sample.group), ...
    rawMap.numberSectionsPresent, analysisMap.numberSectionsPresent, ...
    analysisIncluded, strjoin(string(excludedSectionIndices), ";"), ...
    exclusionReason, ...
    registration.numberSharedRegions, ...
    registration.centroidRmsePixels, ...
    registration.initialShapeScorePixels, ...
    insideFraction, matchingFraction, medianMatchingDistance, ...
    registration.initialSignX, registration.initialSignY, ...
    registration.affineDeterminant, ...
    'VariableNames', {'sample', 'group', 'number_sections_input', ...
    'number_sections_used', 'analysis_included', ...
    'excluded_section_indices', 'exclusion_reason', ...
    'number_shared_regions', 'regional_centroid_RMSE_pixels', ...
    'initial_whole_shape_score_pixels', ...
    'fraction_points_inside_reference_tissue', ...
    'fraction_points_within_5px_of_matching_region', ...
    'median_distance_to_matching_region_pixels', ...
    'initial_PCA_sign_X', 'initial_PCA_sign_Y', ...
