function coordinates = transformSectionCoordinates( ...
        coordinates, rotationDegrees, mirrorLeftRight)
center = median(coordinates, 1, 'omitnan');
coordinates = coordinates - center;
if mirrorLeftRight
    coordinates(:, 1) = -coordinates(:, 1);
end
angle = deg2rad(rotationDegrees);
rotation = [cos(angle), -sin(angle); sin(angle), cos(angle)];
coordinates = coordinates * rotation';
coordinates = coordinates - min(coordinates, [], 1);
end


function [registered, result] = registerWholeMap( ...
        coordinates, regions, reference)
shapeKeep = evenlySpacedIndices(size(coordinates, 1), 50000);
shapeCoordinates = coordinates(shapeKeep, :);
[shapeCandidates, shapeScores, signCandidates] = ...
    initializeWholeShapeCandidates( ...
    coordinates, shapeCoordinates, reference);

bestSelectionScore = inf;
registered = [];
registeredCentroids = [];
referenceCentroids = [];
similarityDeterminant = NaN;
initialShape = NaN;
signX = NaN;
signY = NaN;
for candidateIndex = 1:numel(shapeCandidates)
    initialAll = shapeCandidates{candidateIndex};
    [movingCandidate, fixedCandidate, ~] = ...
        sharedRegionCentroids(initialAll, regions, reference);
    if size(movingCandidate, 1) >= 2
        [candidateRegistered, candidateCentroids, ...
            candidateDeterminant] = applyNonreflectiveSimilarity( ...
            initialAll, movingCandidate, fixedCandidate);
    else
        candidateRegistered = initialAll;
        candidateCentroids = movingCandidate;
        candidateDeterminant = NaN;
    end

    scoreKeep = evenlySpacedIndices(size(candidateRegistered, 1), 30000);
    [~, candidateMatchingFraction, candidateMedianDistance] = ...
        registrationCoverage( ...
        candidateRegistered(scoreKeep, :), regions(scoreKeep), reference);
    selectionScore = candidateMedianDistance + ...
        20 .* (1 - candidateMatchingFraction) + ...
        0.10 .* shapeScores(candidateIndex);
    if selectionScore < bestSelectionScore
        bestSelectionScore = selectionScore;
        registered = candidateRegistered;
        registeredCentroids = candidateCentroids;
        referenceCentroids = fixedCandidate;
        similarityDeterminant = candidateDeterminant;
        initialShape = shapeScores(candidateIndex);
        signX = signCandidates(candidateIndex, 1);
        signY = signCandidates(candidateIndex, 2);
    end
end

% Refine only the selected whole-map solution. Two modest passes allow the
% smooth field to approach the landmarks without permitting affine shear.
for refinementPass = 1:2
    registered = applySmoothLandmarkWarp( ...
        registered, registeredCentroids, referenceCentroids, reference);
    [registeredCentroids, ~, sharedRegionNames] = ...
        sharedRegionCentroids(registered, regions, reference);
end
residual = registeredCentroids - referenceCentroids;
centroidRmse = sqrt(mean(sum(residual .^ 2, 2)));

result = struct( ...
    'numberSharedRegions', numel(sharedRegionNames), ...
    'centroidRmsePixels', centroidRmse, ...
    'initialShapeScorePixels', initialShape, ...
    'initialSignX', signX, ...
    'initialSignY', signY, ...
    'affineDeterminant', similarityDeterminant, ...
    'registeredCentroids', registeredCentroids, ...
    'referenceCentroids', referenceCentroids, ...
    'sharedRegionNames', sharedRegionNames);
end


function [candidates, scores, signCandidates] = ...
        initializeWholeShapeCandidates( ...
        allCoordinates, shapeCoordinates, reference)
referencePoints = reference.unionPoints;
[sourceCenter, sourceVectors, sourceSpans] = ...
    principalCoordinateSystem(shapeCoordinates);
[referenceCenter, referenceVectors, referenceSpans] = ...
    principalCoordinateSystem(referencePoints);

sourceScoresAll = (allCoordinates - sourceCenter) * sourceVectors;
sourceScoresShape = (shapeCoordinates - sourceCenter) * sourceVectors;
scale = referenceSpans ./ sourceSpans;
signCandidates = [1, 1; -1, 1; 1, -1; -1, -1];
distanceImage = bwdist(reference.unionMask);
candidates = cell(size(signCandidates, 1), 1);
scores = nan(size(signCandidates, 1), 1);
for candidateIndex = 1:size(signCandidates, 1)
    signs = signCandidates(candidateIndex, :);
    candidateScores = sourceScoresShape .* scale .* signs;
    mappedShape = candidateScores * referenceVectors' + referenceCenter;
    scores(candidateIndex) = pointToMaskDistance( ...
        mappedShape, distanceImage, reference);
    mappedScores = sourceScoresAll .* scale .* signs;
    candidates{candidateIndex} = ...
        mappedScores * referenceVectors' + referenceCenter;
end
end


function [center, vectors, spans] = principalCoordinateSystem(points)
center = median(points, 1, 'omitnan');
centered = points - center;
covariance = cov(centered, 'omitrows');
[vectors, values] = eig(covariance, 'vector');
[~, order] = sort(values, 'descend');
vectors = vectors(:, order);
scores = centered * vectors;
spans = prctile(scores, 95, 1) - prctile(scores, 5, 1);
spans(spans <= 0) = 1;
end


function score = pointToMaskDistance(points, distanceImage, reference)
columns = points(:, 1);
rows = reference.height + 1 - points(:, 2);
insideCanvas = columns >= 1 & columns <= reference.width & ...
    rows >= 1 & rows <= reference.height;
distances = repmat(0.25 .* max(reference.width, reference.height), ...
    size(columns));
distances(insideCanvas) = interp2( ...
    distanceImage, columns(insideCanvas), rows(insideCanvas), ...
    'linear', max(reference.width, reference.height));
score = mean(min(distances, 50), 'omitnan');
end


function [movingCentroids, fixedCentroids, sharedRegionNames] = ...
        sharedRegionCentroids(coordinates, regions, reference)
movingCentroids = [];
fixedCentroids = [];
sharedRegionNames = strings(0, 1);
for regionIndex = 1:numel(reference.regionNames)
    regionName = reference.regionNames(regionIndex);
    mask = regions == regionName;
    if any(mask)
        movingCentroids(end + 1, :) = ... %#ok<AGROW>
            mean(coordinates(mask, :), 1, 'omitnan');
        fixedCentroids(end + 1, :) = ... %#ok<AGROW>
            reference.centroids(regionIndex, :);
        sharedRegionNames(end + 1, 1) = regionName; %#ok<AGROW>
    end
end
end


function [registered, registeredCentroids, determinantValue] = ...
        applyNonreflectiveSimilarity(coordinates, moving, fixed)
[~, registeredCentroids, transform] = procrustes( ...
    fixed, moving, 'Scaling', true, 'Reflection', false);
translation = transform.c(1, :);
registered = transform.b .* coordinates * transform.T + translation;
determinantValue = det(transform.b .* transform.T);
end


function warped = applySmoothLandmarkWarp( ...
        coordinates, movingLandmarks, fixedLandmarks, reference)
if isempty(movingLandmarks)
    warped = coordinates;
    return
end

displacements = fixedLandmarks - movingLandmarks;
maximumDisplacement = 0.22 .* hypot(reference.width, reference.height);
displacementNorms = vecnorm(displacements, 2, 2);
displacementScale = min(1, ...
    maximumDisplacement ./ max(displacementNorms, eps));
displacements = bsxfun(@times, displacements, displacementScale(:));

boundaryAnchors = [ ...
    1, 1; reference.width, 1; ...
    1, reference.height; reference.width, reference.height; ...
    reference.width ./ 2, 1; reference.width ./ 2, reference.height; ...
    1, reference.height ./ 2; reference.width, reference.height ./ 2];
landmarks = [movingLandmarks; boundaryAnchors];
displacements = [displacements; zeros(size(boundaryAnchors))];
landmarkStrength = [ ...
    repmat(3, size(movingLandmarks, 1), 1); ...
    repmat(0.6, size(boundaryAnchors, 1), 1)];
sigma = 0.16 .* hypot(reference.width, reference.height);

warped = coordinates;
chunkSize = 100000;
for firstRow = 1:chunkSize:size(coordinates, 1)
    lastRow = min(firstRow + chunkSize - 1, size(coordinates, 1));
    chunk = coordinates(firstRow:lastRow, :);
    deltaX = chunk(:, 1) - landmarks(:, 1)';
    deltaY = chunk(:, 2) - landmarks(:, 2)';
    weights = exp(-(deltaX .^ 2 + deltaY .^ 2) ./ ...
        (2 .* sigma .^ 2)) .* landmarkStrength';
    weights = weights ./ max(sum(weights, 2), eps);
    warped(firstRow:lastRow, :) = chunk + weights * displacements;
end
end


function [insideFraction, matchingFraction, medianMatchingDistance] = ...
        registrationCoverage(coordinates, regions, reference)
columns = round(coordinates(:, 1));
rows = round(reference.height + 1 - coordinates(:, 2));
insideCanvas = columns >= 1 & columns <= reference.width & ...
    rows >= 1 & rows <= reference.height;
insideReference = false(size(columns));
validLinear = sub2ind( ...
    [reference.height, reference.width], ...
    min(max(rows, 1), reference.height), ...
    min(max(columns, 1), reference.width));
insideReference(insideCanvas) = ...
    reference.unionMask(validLinear(insideCanvas));
insideFraction = mean(insideReference);

matching = false(size(columns));
matchingDistances = nan(size(columns));
for regionIndex = 1:numel(reference.regionNames)
    regionMask = regions == reference.regionNames(regionIndex);
    if ~any(regionMask)
        continue
    end
    distanceImage = bwdist(reference.masks(:, :, regionIndex));
    regionCoordinates = coordinates(regionMask, :);
    regionColumns = regionCoordinates(:, 1);
    regionRows = reference.height + 1 - regionCoordinates(:, 2);
    inCanvas = regionColumns >= 1 & regionColumns <= reference.width & ...
        regionRows >= 1 & regionRows <= reference.height;
    distances = repmat(max(reference.width, reference.height), ...
        sum(regionMask), 1);
    distances(inCanvas) = interp2( ...
        distanceImage, regionColumns(inCanvas), regionRows(inCanvas), ...
        'linear', max(reference.width, reference.height));
    matching(regionMask) = distances <= 5;
    matchingDistances(regionMask) = distances;
end
matchingFraction = mean(matching);
medianMatchingDistance = median(matchingDistances, 'omitnan');
end


