function rawMap = loadAndReassembleWholeAnimal(sample, inputFolder, reference)
numberFiles = numel(sample.files);
emptySection = struct( ...
    'coordinates', zeros(0, 2), ...
    'genes', strings(0, 1), ...
    'regions', strings(0, 1), ...
    'fileName', "");
sections = repmat(emptySection, numberFiles, 1);
sectionWidths = zeros(numberFiles, 1);

for fileIndex = 1:numberFiles
    filePath = fullfile(inputFolder, sample.files{fileIndex});
    if ~isfile(filePath)
        error('Missing ExSeq file: %s', filePath);
    end
    options = detectImportOptions(filePath);
    names = string(options.VariableNames);
    geneColumn = findColumn(names, ["gene", "genes", "gene_name"]);
    regionColumn = findColumn(names, ...
        ["region_name", "region", "hippocampal_region"]);
    xColumn = findColumn(names, ["global_x_um", "x_um", "x"]);
    yColumn = findColumn(names, ["global_y_um", "y_um", "y"]);
    selected = [geneColumn, regionColumn, xColumn, yColumn];
    if any(strlength(selected) == 0)
        error('Required columns were not found in %s.', filePath);
    end
    options.SelectedVariableNames = cellstr(selected);
    T = readtable(filePath, options);

    genes = upper(regexprep(strtrim(string(T.(char(geneColumn)))), ...
        '\s+', ''));
    regions = standardizeRegion(T.(char(regionColumn)));
    x = double(T.(char(xColumn)));
    y = double(T.(char(yColumn)));
    keep = isfinite(x) & isfinite(y) & ...
        ismember(regions, reference.regionNames);
    coordinates = [x(keep), y(keep)];
    genes = genes(keep);
    regions = regions(keep);

    [rotationDegrees, mirrorLeftRight] = sectionOrientation( ...
        sample.name, fileIndex);
    coordinates = transformSectionCoordinates( ...
        coordinates, rotationDegrees, mirrorLeftRight);
    sectionWidths(fileIndex) = range(coordinates(:, 1));
    sections(fileIndex) = struct( ...
        'coordinates', coordinates, ...
        'genes', genes, ...
        'regions', regions, ...
        'fileName', string(sample.files{fileIndex}));
    clear T genes regions x y
end

positiveWidths = sectionWidths(sectionWidths > 0);
if isempty(positiveWidths)
    error('No annotated hippocampal molecules found for %s.', sample.name);
end
typicalWidth = median(positiveWidths);
gap = 0.025 .* typicalWidth;
offset = 0;
referenceMedianY = [];
coordinates = zeros(0, 2);
genes = strings(0, 1);
regions = strings(0, 1);
sectionIndices = zeros(0, 1);
sectionFiles = strings(0, 1);
for fileIndex = 1:numberFiles
    section = sections(fileIndex);
    if isempty(section.coordinates)
        continue
    end
    if isempty(referenceMedianY)
        referenceMedianY = median(section.coordinates(:, 2), 'omitnan');
    end
    yOffset = referenceMedianY - ...
        median(section.coordinates(:, 2), 'omitnan');
    yOffset = yOffset + sectionVerticalAdjustment( ...
        sample.name, fileIndex, typicalWidth);
    section.coordinates(:, 1) = section.coordinates(:, 1) + offset;
    section.coordinates(:, 2) = section.coordinates(:, 2) + yOffset;
    coordinates = [coordinates; section.coordinates]; %#ok<AGROW>
    genes = [genes; section.genes]; %#ok<AGROW>
    regions = [regions; section.regions]; %#ok<AGROW>
    sectionIndices = [sectionIndices; ...
        repmat(fileIndex, size(section.coordinates, 1), 1)]; %#ok<AGROW>
    sectionFiles = [sectionFiles; ...
        repmat(section.fileName, size(section.coordinates, 1), 1)]; %#ok<AGROW>
    offset = offset + sectionWidths(fileIndex) + gap;
end

rawMap = struct( ...
    'coordinates', coordinates, ...
    'genes', genes, ...
    'regions', regions, ...
    'sectionIndices', sectionIndices, ...
    'sectionFiles', sectionFiles, ...
    'numberSectionsPresent', sum(sectionWidths > 0));
end


